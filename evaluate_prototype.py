import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import torch
from torch.utils.data import DataLoader

from prototype_dataset import CachedLandmarkCollator, CachedLandmarkDataset
from prototype_model import ASLLiveCaptionPrototype


def confusion_matrix(y_true, y_pred, size):
    matrix = np.zeros((size, size), dtype=np.int64)
    for true, pred in zip(y_true, y_pred):
        matrix[true, pred] += 1
    return matrix


def save_matrix(matrix, labels, title, path):
    fig, ax = plt.subplots(figsize=(max(6, len(labels) * 0.45), max(5, len(labels) * 0.45)))
    im = ax.imshow(matrix, cmap="Blues")
    ax.set_title(title)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    ax.set_xticks(range(len(labels)))
    ax.set_yticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=90, fontsize=7)
    ax.set_yticklabels(labels, fontsize=7)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


def write_notebook(metrics, plots, path):
    try:
        import nbformat as nbf
    except ImportError:
        return

    nb = nbf.v4.new_notebook()
    nb.cells = [
        nbf.v4.new_markdown_cell("# ASL Live Caption Prototype Evaluation"),
        nbf.v4.new_markdown_cell(
            "This notebook was generated by `evaluate_prototype.py` from real prepared WLASL/How2Sign samples."
        ),
        nbf.v4.new_code_cell(f"metrics = {json.dumps(metrics, indent=2)}\nmetrics"),
    ]
    for plot in plots:
        nb.cells.append(nbf.v4.new_markdown_cell(f"![{plot.name}]({plot.name})"))
    with open(path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)


def main():
    parser = argparse.ArgumentParser(description="Evaluate the ASL live caption prototype.")
    parser.add_argument("--checkpoint", default="checkpoints/prototype_best.pt")
    parser.add_argument("--manifest", default="data/prototype_manifest.json")
    parser.add_argument("--split", default="val")
    parser.add_argument("--out-dir", default="eval_outputs")
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    checkpoint = torch.load(args.checkpoint, map_location="cpu")
    manifest = checkpoint.get("manifest")
    if manifest is None:
        with open(args.manifest, "r", encoding="utf-8") as f:
            manifest = json.load(f)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = ASLLiveCaptionPrototype(
        gloss_vocab_size=len(manifest["gloss_to_id"]),
        caption_vocab_size=len(manifest["caption_to_id"]),
        hidden_dim=checkpoint.get("hidden_dim", 96),
        num_heads=checkpoint.get("num_heads", 6),
    ).to(device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    dataset = CachedLandmarkDataset(args.manifest, split=args.split)
    loader = DataLoader(dataset, batch_size=2, shuffle=False, collate_fn=CachedLandmarkCollator())

    gloss_true, gloss_pred = [], []
    caption_true, caption_pred = [], []
    rows = []
    with torch.no_grad():
        for batch in loader:
            hand = batch["hand"].to(device)
            face = batch["face"].to(device)
            pose = batch["pose"].to(device)
            output = model(hand, face, pose)
            gp = output["gloss_logits"].argmax(dim=-1).cpu().tolist()
            cp = output["caption_logits"].argmax(dim=-1).cpu().tolist()

            gloss_true.extend(batch["gloss_ids"].tolist())
            gloss_pred.extend(gp)
            caption_true.extend(batch["caption_ids"].tolist())
            caption_pred.extend(cp)
            for i, pred_id in enumerate(cp):
                rows.append({
                    "dataset": batch["datasets"][i],
                    "actual_gloss": batch["glosses"][i],
                    "actual_caption": batch["captions"][i],
                    "pred_caption_id": pred_id,
                    "pred_caption": dataset.id_to_caption.get(pred_id, "<unk>"),
                })

    gloss_acc = float(np.mean(np.array(gloss_true) == np.array(gloss_pred))) if gloss_true else 0.0
    caption_acc = float(np.mean(np.array(caption_true) == np.array(caption_pred))) if caption_true else 0.0
    metrics = {
        "split": args.split,
        "num_samples": len(gloss_true),
        "gloss_accuracy": gloss_acc,
        "caption_accuracy": caption_acc,
        "predictions": rows,
    }

    with open(out_dir / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    gloss_labels = [label for label, _ in sorted(manifest["gloss_to_id"].items(), key=lambda item: item[1])]
    caption_labels = [label[:32] for label, _ in sorted(manifest["caption_to_id"].items(), key=lambda item: item[1])]
    plots = []
    gloss_matrix = confusion_matrix(gloss_true, gloss_pred, len(gloss_labels))
    gloss_plot = out_dir / "gloss_confusion.png"
    save_matrix(gloss_matrix, gloss_labels, "Gloss Confusion Matrix", gloss_plot)
    plots.append(gloss_plot)

    caption_matrix = confusion_matrix(caption_true, caption_pred, len(caption_labels))
    caption_plot = out_dir / "caption_confusion.png"
    save_matrix(caption_matrix, caption_labels, "Caption Confusion Matrix", caption_plot)
    plots.append(caption_plot)

    write_notebook(metrics, plots, out_dir / "evaluation_report.ipynb")
    print(f"Saved evaluation outputs to {out_dir}")
    print(json.dumps({k: metrics[k] for k in ("split", "num_samples", "gloss_accuracy", "caption_accuracy")}, indent=2))


if __name__ == "__main__":
    main()
